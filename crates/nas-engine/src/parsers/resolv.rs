//! Parser de `/etc/resolv.conf`.

/// Extrae los servidores DNS declarados, conservando el orden y sin duplicados.
pub fn parse_nameservers(text: &str) -> Vec<String> {
    let mut servers: Vec<String> = Vec::new();

    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
            continue;
        }

        let mut parts = line.split_whitespace();
        if !parts
            .next()
            .is_some_and(|key| key.eq_ignore_ascii_case("nameserver"))
        {
            continue;
        }

        if let Some(server) = parts.next() {
            let server = server.to_string();
            if !servers.contains(&server) {
                servers.push(server);
            }
        }
    }

    servers
}

#[cfg(test)]
mod tests {
    use super::parse_nameservers;

    #[test]
    fn extrae_dns_sin_duplicados() {
        let conf = "\
# Generated by dhcpcd from eno1.dhcp
nameserver 10.16.0.23
nameserver 10.16.0.60
nameserver 10.16.0.23
search oficina.local
";
        assert_eq!(parse_nameservers(conf), vec!["10.16.0.23", "10.16.0.60"]);
    }

    #[test]
    fn archivo_vacio_devuelve_lista_vacia() {
        assert!(parse_nameservers("").is_empty());
    }
}
